"""Rebuild the checked-in local survey sector from the retained OSM snapshot (ODbL)."""
import json
import math
from pathlib import Path
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
xml = ET.parse(root / 'research/hornsea/site.osm').getroot()
members = {m.get('ref') for m in xml.find('relation').findall('member') if m.get('role') == 'generator'}
nodes = []
for n in xml.findall('node'):
    tags = {t.get('k'): t.get('v') for t in n.findall('tag')}
    if n.get('id') in members and tags.get('power') == 'generator':
        nodes.append(dict(osmId=n.get('id'), ref=tags['ref'], latitude=float(n.get('lat')), longitude=float(n.get('lon'))))
origin = next(n for n in nodes if n['ref'] == 'G33')
# Local equirectangular projection, WGS84; +X east, -Z north. Approximate metres, not survey control.
for n in nodes:
    n['x'] = round(math.radians(n['longitude'] - origin['longitude']) * 6378137 * math.cos(math.radians(origin['latitude'])), 3)
    n['z'] = round(-math.radians(n['latitude'] - origin['latitude']) * 6378137, 3)
sector = sorted(nodes, key=lambda n: (n['x'] ** 2 + n['z'] ** 2, n['osmId']))[:12]
data = dict(origin={k: origin[k] for k in ['latitude', 'longitude']}, sourceRelation=11343101, sourceGeneratorCount=len(nodes), turbines=sector)
encoded = json.dumps(data, ensure_ascii=False, indent=2) + '\n'
(root / 'public/assets/hornsea/turbines.json').write_text(encoded, encoding='utf-8')
folder = root / 'src/environments/hornsea'
folder.mkdir(parents=True, exist_ok=True)
(folder / 'survey.ts').write_text('// Generated by scripts/extract-hornsea.py. © OpenStreetMap contributors, ODbL 1.0.\nexport const hornseaSurvey = ' + encoded.rstrip() + ' as const;\n', encoding='utf-8')
print(f'Exported {len(sector)} of {len(nodes)} mapped generators around G33; this is not the complete 165-turbine site.')

"""Build the Ninepin mesh from retained OSM coastlines and HK LandsD 5 m DTM.
Offline build-only dependencies: numpy, pyproj, shapely >= 2.1. Runtime only needs Three.js.
"""
import json, math, zipfile
from pathlib import Path
import xml.etree.ElementTree as ET
from collections import Counter
import numpy as np
from pyproj import Transformer
from shapely import Polygon, box, constrained_delaunay_triangles

root=Path(__file__).resolve().parents[1]
folder=root/'research/ninepin'; out=root/'public/assets/ninepin'
project=Transformer.from_crs(4326,2326,always_xy=True)
lon,lat=114.3565,22.2635
origin_e,origin_n=project.transform(lon,lat)
cache=folder/'dtm-crop.npz'
if not cache.exists():
    with zipfile.ZipFile(folder/'Whole_HK_DTM_5m.zip') as archive:
        with archive.open('Whole_HK_DTM_5m.asc') as f:
            header={}
            for _ in range(6):
                k,v=f.readline().decode().split();header[k.lower()]=float(v)
            cell=header['cellsize'];left=header['xllcorner']+cell/2;top=header['yllcorner']+(header['nrows']-.5)*cell
            c0=int((origin_e-3000-left)//cell);c1=int((origin_e+3000-left)//cell)+2
            r0=int((top-origin_n-3000)//cell);r1=int((top-origin_n+3000)//cell)+2
            rows=[]
            for r,line in enumerate(f):
                if r>r1:break
                if r>=r0:rows.append(np.fromstring(line.decode(),sep=' ',dtype=np.float32)[c0:c1])
            np.savez_compressed(cache,grid=np.array(rows),left=left+c0*cell,top=top-r0*cell,cell=cell)
d=np.load(cache);grid=d['grid'];left=float(d['left']);top=float(d['top']);cell=float(d['cell'])
missing=0
def height(x,z):
    global missing
    col=(origin_e+x-left)/cell;row=(top-(origin_n-z))/cell;i=int(row);j=int(col);u=col-j;v=row-i
    patch=grid[i:i+2,j:j+2].astype(float)
    valid=patch>-9000
    if not valid.any():missing+=1;return .6
    patch[~valid]=0
    # Clamp only the exposed mapped shore to a small positive height. No random vertical relief.
    return round(max(.6,patch[0,0]*(1-u)*(1-v)+patch[0,1]*u*(1-v)+patch[1,0]*(1-u)*v+patch[1,1]*u*v),3)
xml=ET.parse(folder/'site.osm').getroot()
nodes={n.get('id'):(float(n.get('lon')),float(n.get('lat'))) for n in xml.findall('node')}
islands=[]
for way in xml.findall('way'):
    tags={t.get('k'):t.get('v') for t in way.findall('tag')}
    if tags.get('natural')!='coastline':continue
    refs=[n.get('ref') for n in way.findall('nd')]
    if refs[0]!=refs[-1]:raise ValueError('Unclosed coastline')
    coast=[]
    for ref in refs[:-1]:
        e,n=project.transform(*nodes[ref]);coast.append([round(e-origin_e,3),round(origin_n-n,3)])
    poly=Polygon(coast)
    if not poly.is_valid:raise ValueError(f'Invalid coastline {way.get("id")}')
    if poly.area<4:continue
    vertices=[];indices=[];lookup={}
    def vertex(x,z):
        key=(round(x,3),round(z,3))
        if key not in lookup:
            lookup[key]=len(vertices)//3;vertices.extend([key[0],height(*key),key[1]])
        return lookup[key]
    x0,z0,x1,z1=poly.bounds;step=10
    covered=0
    for x in range(math.floor(x0/step)*step,math.ceil(x1/step)*step,step):
        for z in range(math.floor(z0/step)*step,math.ceil(z1/step)*step,step):
            clipped=poly.intersection(box(x,z,x+step,z+step))
            if clipped.area<1e-8:continue
            for tri in constrained_delaunay_triangles(clipped).geoms:
                pts=list(tri.exterior.coords)[:3]
                if tri.area<1e-8:continue
                covered+=tri.area
                # Positive Y normals: clockwise in XZ.
                a,b,c=pts
                if (b[0]-a[0])*(c[1]-a[1])-(b[1]-a[1])*(c[0]-a[0])>0:pts.reverse()
                ids=[vertex(*p) for p in pts]
                if len(set(ids))==3:indices.extend(ids)
    assert abs(covered-poly.area)<.01,(way.get('id'),covered,poly.area)
    name={'9559752':'南果洲','9562498':'北果洲'}.get(way.get('id'),tags.get('name:zh',tags.get('name',f'岩礁 {way.get("id")}')))
    islands.append(dict(osmId=way.get('id'),name=name,coast=coast,positions=vertices,indices=indices,maxHeight=max(vertices[1::3]),area=round(poly.area,2)))
islands.sort(key=lambda i:-i['area'])
data=dict(origin=dict(latitude=lat,longitude=lon,easting=origin_e,northing=origin_n,crs='EPSG:2326',verticalDatum='Hong Kong Principal Datum'),meshStep=10,sourceGrid=5,missingSamples=missing,islands=islands)
encoded=json.dumps(data,ensure_ascii=False,separators=(',',':'))
out.mkdir(parents=True,exist_ok=True);(out/'terrain.json').write_text(encoded,encoding='utf-8')
src=root/'src/environments/ninepin';src.mkdir(parents=True,exist_ok=True)
(src/'survey.ts').write_text('// Generated by scripts/extract-ninepin.py. Source rights: public/assets/ninepin/sources.json.\nexport const ninepinSurvey = '+encoded+';\n',encoding='utf-8')
print(json.dumps(dict(islands=len(islands),vertices=sum(len(i['positions'])//3 for i in islands),triangles=sum(len(i['indices'])//3 for i in islands),missingSamples=missing,heights=[(i['name'],i['maxHeight']) for i in islands]),ensure_ascii=False))
